type Optional = "categoryFirstVisit" | "similarJobs" | "brands" | "phone" | "since" | "servicesMonth" | "region";
type Base = Omit<Technician, Optional> & Partial<Pick<Technician, Optional>>;

const regionOf = ({ x, y }: { x: number; y: number }) =>
  y > 62 ? "Zona Sul" : x < 35 ? "Zona Oeste" : x > 65 ? "Zona Leste" : y < 30 ? "Zona Norte" : "Centro";

const phoneOf = (id: string) => {
  let h = 7;
  for (const ch of id) h = (h * 31 + ch.charCodeAt(0)) % 1_000_000_007;
  return `(11) 9${String(1000 + (h % 9000))}-${String(1000 + ((h >> 5) % 9000))}`;
};

